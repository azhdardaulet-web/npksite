-- Проверяем, что каждый пункт меню из mapping существует в БД.
DO $$
DECLARE
  missing_labels text;
BEGIN
  SELECT string_agg(source.label_ru, ', ' ORDER BY source.label_ru)
  INTO missing_labels
  FROM (
    VALUES
      ('О партии'),
      ('История партии'),
      ('Руководство'),
      ('Устав'),
      ('Программа'),
      ('Проекты'),
      ('Фракция'),
      ('О фракции'),
      ('Состав фракции'),
      ('Депутатские запросы'),
      ('Общественная приёмная'),
      ('Филиалы'),
      ('Пресс-центр'),
      ('Новости и релизы'),
      ('СМИ о нас'),
      ('Галерея'),
      ('О портале «Халық үні Қазақстан»'),
      ('Народный подкаст'),
      ('Видео'),
      ('Контакты'),
      ('Магазин')
  ) AS source(label_ru)
  WHERE NOT EXISTS (
    SELECT 1
    FROM public.menu_items AS menu_item
    WHERE menu_item.label_ru = source.label_ru
  );

  IF missing_labels IS NOT NULL THEN
    RAISE EXCEPTION
      'Не найдены пункты меню: %. Обновление отменено.',
      missing_labels;
  END IF;
END
$$;

