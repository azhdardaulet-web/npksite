-- Контракт миграции: page_blocks содержит парные скалярные поля
-- title_*, heading_*, subtitle_* и text_*. RU-поля не изменяются.
DO $$
DECLARE
  missing_columns text;
BEGIN
  SELECT string_agg(source.column_name, ', ' ORDER BY source.column_name)
  INTO missing_columns
  FROM (
    VALUES
      ('title_ru'), ('title_kz'),
      ('heading_ru'), ('heading_kz'),
      ('subtitle_ru'), ('subtitle_kz'),
      ('text_ru'), ('text_kz')
  ) AS source(column_name)
  WHERE NOT EXISTS (
    SELECT 1
    FROM information_schema.columns AS column_info
    WHERE column_info.table_schema = 'public'
      AND column_info.table_name = 'page_blocks'
      AND column_info.column_name = source.column_name
  );

  IF missing_columns IS NOT NULL THEN
    RAISE EXCEPTION
      'В public.page_blocks отсутствуют поля: %. Обновление отменено.',
      missing_columns;
  END IF;
END
$$;

