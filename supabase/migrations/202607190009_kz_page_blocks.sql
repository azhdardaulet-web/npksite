-- Показываем только строки, в которых после миграции заполнено хотя бы одно KZ-поле.
SELECT id, title_kz, heading_kz, subtitle_kz, text_kz
FROM public.page_blocks
WHERE nullif(btrim(coalesce(title_kz, '')), '') IS NOT NULL
   OR nullif(btrim(coalesce(heading_kz, '')), '') IS NOT NULL
   OR nullif(btrim(coalesce(subtitle_kz, '')), '') IS NOT NULL
   OR nullif(btrim(coalesce(text_kz, '')), '') IS NOT NULL
ORDER BY id;
