BEGIN;

-- Проверяем наличие всех новостей, для которых в источнике есть KZ-заголовок.
DO $$
DECLARE
  missing_titles text;
BEGIN
  SELECT string_agg(source.title_ru, ' | ' ORDER BY source.title_ru)
  INTO missing_titles
  FROM (
    VALUES
      ('От обещаний — к гарантиям!'),
      ('Нурсултан Шоканов избран председателем Народной партии Казахстана'),
      ('Последний аккорд'),
      ('Долг в жизни'),
      ('НПК представила план строительства 50 новых школ в сельской местности'),
      ('Сельхозпроизводители получат дополнительные субсидии на технику'),
      ('Народная приемная помогла решить более 850 обращений граждан'),
      ('Фракция НПК инициировала закон о защите прав трудящихся'),
      ('Региональные отделения партии провели день открытых дверей'),
      ('НПК запустила программу бесплатной юридической помощи гражданам')
  ) AS source(title_ru)
  WHERE NOT EXISTS (
    SELECT 1 FROM public.news AS news_item WHERE news_item.title_ru = source.title_ru
  );

  IF missing_titles IS NOT NULL THEN
    RAISE EXCEPTION 'Не найдены новости: %. Обновление отменено.', missing_titles;
  END IF;
END
$$;

UPDATE public.news AS news_item
SET title_kz = source.title_kz
FROM (
  VALUES
    ('От обещаний — к гарантиям!', 'Уәдеден — кепілдікке!'),
    ('Нурсултан Шоканов избран председателем Народной партии Казахстана', 'Нұрсұлтан Шоқанов Қазақстан Халық партиясының төрағасы болып сайланды'),
    ('Последний аккорд', 'Соңғы аккорд'),
    ('Долг в жизни', 'Өмірдегі парыз'),
    ('НПК представила план строительства 50 новых школ в сельской местности', 'ҚХП ауылдық жерлерде 50 жаңа мектеп салу жоспарын ұсынды'),
    ('Сельхозпроизводители получат дополнительные субсидии на технику', 'Ауыл шаруашылығы өндірушілеріне техника алуға қосымша субсидия беріледі'),
    ('Народная приемная помогла решить более 850 обращений граждан', 'Қоғамдық қабылдау азаматтардың 850-ден астам өтінішін шешуге көмектесті'),
    ('Фракция НПК инициировала закон о защите прав трудящихся', 'ҚХП фракциясы еңбеккерлердің құқығын қорғау туралы заңға бастамашы болды'),
    ('Региональные отделения партии провели день открытых дверей', 'Партияның өңірлік бөлімшелері ашық есік күнін өткізді'),
    ('НПК запустила программу бесплатной юридической помощи гражданам', 'ҚХП азаматтарға тегін заңгерлік көмек көрсету бағдарламасын іске қосты')
) AS source(title_ru, title_kz)
WHERE news_item.title_ru = source.title_ru;

-- Excerpt обновляется только у четырёх новостей, где он явно дан в источнике.
UPDATE public.news AS news_item
SET excerpt_kz = source.excerpt_kz
FROM (
  VALUES
    ('От обещаний — к гарантиям!', 'Сайлауалды уәделерден азаматтарға берілетін нақты кепілдіктерге көшу — партияның басты басымдығы.'),
    ('Нурсултан Шоканов избран председателем Народной партии Казахстана', 'Кезектен тыс съезде делегаттар партияның жаңа басшысын бірауыздан қолдады.'),
    ('Последний аккорд', 'Саяси маусымның қорытындысы: партия не істеп үлгерді және жаңа жылда қандай міндеттер тұр?'),
    ('Долг в жизни', 'Қазіргі Қазақстан қоғамындағы азаматтық жауапкершілік пен жеке парыз туралы.')
) AS source(title_ru, excerpt_kz)
WHERE news_item.title_ru = source.title_ru;

COMMIT;

SELECT title_ru, title_kz, excerpt_kz
FROM public.news
WHERE title_ru IN (
  'От обещаний — к гарантиям!',
  'Нурсултан Шоканов избран председателем Народной партии Казахстана',
  'Последний аккорд',
  'Долг в жизни',
  'НПК представила план строительства 50 новых школ в сельской местности',
  'Сельхозпроизводители получат дополнительные субсидии на технику',
  'Народная приемная помогла решить более 850 обращений граждан',
  'Фракция НПК инициировала закон о защите прав трудящихся',
  'Региональные отделения партии провели день открытых дверей',
  'НПК запустила программу бесплатной юридической помощи гражданам'
)
ORDER BY published_at DESC NULLS LAST, title_ru;
