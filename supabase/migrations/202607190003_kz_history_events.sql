BEGIN;

-- Проверяем наличие всех событий, для которых есть вычитанный KZ-текст.
DO $$
DECLARE
  missing_years text;
BEGIN
  SELECT string_agg(source.year::text, ', ' ORDER BY source.year)
  INTO missing_years
  FROM (
    VALUES (2011), (2016), (2020), (2021), (2022), (2026)
  ) AS source(year)
  WHERE NOT EXISTS (
    SELECT 1
    FROM public.history_events AS history_event
    WHERE history_event.year = source.year
  );

  IF missing_years IS NOT NULL THEN
    RAISE EXCEPTION
      'Не найдены события за годы: %. Обновление отменено.',
      missing_years;
  END IF;
END
$$;

UPDATE public.history_events AS history_event
SET text_kz = source.text_kz
FROM (
  VALUES
    (
      2011,
      '2011 жылғы 26 қарашада Қазақстан Коммунистік халық партиясының VI кезектен тыс съезі өтті. Съезде 2012 жылғы Мәжіліс сайлауына қатысатын 23 кандидат бекітілді. Олардың арасында Владислав Косарев пен 2011 жылғы президенттік сайлауға қатысқан Жамбыл Ахметбеков бар еді.'
    ),
    (
      2016,
      'Партия Парламентке өтті. Партия өкілдері сайлау әділ өткенін, бұқаралық ақпарат құралдарына еркін қол жеткізілгенін және елеулі заң бұзушылық тіркелмегенін мәлімдеді.'
    ),
    (
      2020,
      '2020 жылғы 11 қарашада өткен XV кезектен тыс съезде Қазақстан Коммунистік халық партиясының атауы Қазақстан Халық партиясы болып өзгертілді. Партияның жарғысы мен бағдарламасына тиісті өзгерістер енгізілді.'
    ),
    (
      2021,
      'Нұр-Сұлтан қаласында XVII кезектен тыс съезд өтті. Съезде Мәжіліс пен мәслихаттардың 2021 жылғы сайлау қорытындысы шығарылып, фракция өкілдері сайланды.'
    ),
    (
      2022,
      '2022 жылғы 28 наурызда өткен XIX кезектен тыс съезде Ермұхамет Ертісбаев партия төрағасы болып сайланды. Айқын Қоңыров партия төрағасының бірінші орынбасары қызметіне тағайындалды.'
    ),
    (
      2026,
      'Партияның бұрынғы төрағасы өкілеттігін тоқтатты. 2026 жылғы 27 маусымда өткен кезектен тыс съезде Нұрсұлтан Шоқанов Қазақстан Халық партиясының төрағасы болып сайланды.'
    )
) AS source(year, text_kz)
WHERE history_event.year = source.year;

COMMIT;

-- Заголовки не обновляются: их KZ-переводов нет в единственном источнике.
SELECT year, text_kz
FROM public.history_events
WHERE year IN (2011, 2016, 2020, 2021, 2022, 2026)
ORDER BY year;
